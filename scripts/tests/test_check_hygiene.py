"""Tests for scripts/check_hygiene.py (standard library only; runs on any OS).

Forbidden words are assembled from pieces so this file passes the check itself.
"""

import subprocess
import sys
from pathlib import Path

import pytest

import check_hygiene as hy

REPO_ROOT = Path(__file__).resolve().parents[2]

PHASE = "Pha" + "se"
PROMPT = "Pro" + "mpt"
TOOL = "Cla" + "ude"
TRAILER = "Co-" + "Authored-By"


def rules(text: str) -> list[str]:
    return [rule for _, rule, _ in hy.scan_text(text)]


@pytest.mark.parametrize("text", [f"{PHASE} 2", f"{PHASE.lower()}-2", f"{PHASE.upper()}_3",
                                  f"{PHASE}2"])
def test_phase_numbers(text):
    assert rules(text) == ["phase_number"]


@pytest.mark.parametrize("text", [f"{PROMPT} 2.4", f"{PROMPT.lower()}-2", f"{PROMPT} 12"])
def test_prompt_numbers(text):
    assert rules(text) == ["prompt_number"]


@pytest.mark.parametrize("text", [TOOL, TOOL.upper(), "Chat" + "GPT", "Co" + "pilot",
                                  "Open" + "AI", "A" + "I assistant", "generated by a" + "n AI"])
def test_ai_tool_names(text):
    assert rules(f"written with {text} here") == ["ai_tool"]


def test_attribution_trailer():
    assert rules(f"{TRAILER}: Someone <a@b.c>") == ["attribution"]


@pytest.mark.parametrize("text", [
    "The trial phase and the warm-up phase are timed separately.",
    "Shows a prompt before 2 runs.",
    "OpenCppCoverage measures line coverage.",
    "per-channel quantization, phases of the run",
])
def test_ordinary_wording_passes(text):
    assert rules(text) == []


def test_exempt_marker_skips_only_its_line():
    text = f"{PHASE} 1 {hy.EXEMPT_MARKER}\n{PHASE} 2"
    assert hy.scan_text(text) == [(2, "phase_number", f"{PHASE} 2")]


def test_files(tmp_path):
    (tmp_path / "ok.md").write_text("fine\n")
    (tmp_path / "bad.md").write_text(f"line one\nsee {PROMPT} 3\n")
    (tmp_path / "blob.bin").write_bytes(b"\0" + f"{PHASE} 9".encode())
    (tmp_path / "big.txt").write_bytes(b"x" * (hy.MAX_FILE_BYTES + 1))
    (tmp_path / (TOOL + ".md")).write_text("notes\n")  # the local-only notes file
    findings = hy.check_files(tmp_path, ["ok.md", "bad.md", "blob.bin", "big.txt",
                                         TOOL + ".md"])
    assert sorted((f.where, f.rule) for f in findings) == [
        (TOOL + ".md", "local_only_file"),
        ("bad.md:2", "prompt_number"),
        ("big.txt", "large_file"),
    ]


def test_large_file_allowlist_holds_only_the_full_evaluation_manifest():
    assert hy.LARGE_FILE_ALLOWLIST == {"datasets/imagenetv2-matched-frequency/eval-full.tsv"}


def test_commit_messages():
    findings = hy.check_messages([("a" * 40, f"Add a thing\n\n{TRAILER}: x"),
                                  ("b" * 40, "Fix another thing")])
    assert [(f.where, f.rule) for f in findings] == [("commit aaaaaaaaaaaa line 3", "attribution")]


def test_repository_is_clean():
    result = subprocess.run([sys.executable, str(REPO_ROOT / "scripts" / "check_hygiene.py")],
                            cwd=REPO_ROOT, capture_output=True, text=True)
    assert result.returncode == 0, result.stdout + result.stderr
